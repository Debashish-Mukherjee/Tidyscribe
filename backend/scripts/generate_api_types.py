"""Generate TypeScript schema types from FastAPI's OpenAPI contract without running the server."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.main import app


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return f'ApiSchemas["{schema["$ref"].rsplit("/", 1)[-1]}"]'
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(ts_type(item) for item in schema[union])
    if "allOf" in schema:
        return " & ".join(ts_type(item) for item in schema["allOf"])
    if "enum" in schema:
        import json
        return " | ".join(json.dumps(value) for value in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        return f'Array<{ts_type(schema.get("items", {}))}>'
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = [f'"{name}"{"" if name in required else "?"}: {ts_type(value)};' for name, value in schema.get("properties", {}).items()]
        extra = schema.get("additionalProperties")
        if extra:
            fields.append(f'[key: string]: {ts_type(extra) if isinstance(extra, dict) else "unknown"};')
        return "{ " + " ".join(fields) + " }" if fields else "Record<string, unknown>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schemas = app.openapi()["components"]["schemas"]
    result = "// Generated by backend/scripts/generate_api_types.py. Do not edit.\nexport type ApiSchemas = {\n"
    result += "".join(f'  "{name}": {ts_type(schema)};\n' for name, schema in sorted(schemas.items()))
    result += "};\n"
    destination = Path(__file__).resolve().parents[2] / "frontend/lib/api-schema.ts"
    if args.check:
        if not destination.exists() or destination.read_text() != result:
            raise SystemExit("API types are stale; run backend/scripts/generate_api_types.py")
        print("API types match the OpenAPI contract")
    else:
        destination.write_text(result)
        print(f"Generated {len(schemas)} API schemas")


if __name__ == "__main__":
    main()
